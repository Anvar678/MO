"""Формирование отчёта Markdown из результатов расчёта."""


def table(headers, rows):
    def row(values):
        return '| ' + ' | '.join(map(str, values)) + ' |'
    return '\n'.join([row(headers), row(['---'] * len(headers)), *[row(values) for values in rows]])


def write_report(path, data, scenarios, plans, checks, heuristics, comparisons, scaling, repeats):
    base, deficit, stress = scenarios
    tight, large, cuts = comparisons
    input_table = table(
        ['Кандидат', 'Роль', 'Часы', *[team['id'] for team in data['teams']]],
        [(person['id'], person['role'], person['hours'], *scores)
         for person, scores in zip(data['candidates'], data['scores'])],
    )
    scenario_table = table(
        ['Сценарий', 'Недоступны', 'Новая несовместимая пара', 'Доп. часы на команду', 'Статус',
         'Оценка, баллы', 'Изменение', 'Верхняя граница', 'Зазор HiGHS, %'],
        [(s['scenario'], s['unavailable'] or '—', s['extra_conflicts'] or '—', s['extra_required_hours'],
          s['status'], f"{s['score']:.2f}", f"{s['change_from_base']:+.2f}", f"{s['best_bound']:.2f}",
          f"{s['mip_gap_pct']:.2f}") for s in scenarios],
    )
    scenario_names = {s['id']: s['scenario'] for s in scenarios}
    plan_table = table(
        ['Сценарий и метод', 'Команда', 'Назначения', 'Свои часы', 'Требуется', 'Резерв, ч', 'Активация',
         'Оценка до расходов', 'Расходы, баллы'],
        [(f"{scenario_names[p['scenario']]} / {p['method']}", p['team'], p['members'],
          f"{p['internal_hours']:.2f}", int(p['required_hours']), f"{p['reserve_hours']:.2f}",
          f"{p['reserve_on']:.3g}", f"{p['gross_score']:.2f}", f"{p['reserve_cost']:.2f}")
         for p in plans if p['method'] in ('LP', 'MILP')],
    )
    check_table = table(
        ['Сценарий', 'Метод', 'Независимая оценка', 'Расхождение цели', 'Максимальное нарушение'],
        [(scenario_names[r['scenario']], r['method'], f"{r['score_recalculated']:.2f}",
          '—' if r['objective_error'] is None else f"{r['objective_error']:.2e}", f"{r['max_violation']:.2e}")
         for r in checks],
    )
    greedy_table = table(
        ['Сценарий', 'Статус эвристики', 'MILP, баллы', 'Эвристика, баллы', 'Потеря, %',
         'MILP, мс', 'Эвристика, мс'],
        [(h['scenario'], h['greedy_status'], f"{h['milp_score']:.2f}",
          '—' if h['greedy_score'] is None else f"{h['greedy_score']:.2f}",
          '—' if h['shortfall_pct'] is None else f"{h['shortfall_pct']:.2f}",
          f"{h['milp_median_ms']:.3f}", f"{h['greedy_median_ms']:.3f}") for h in heuristics],
    )
    formulation_table = table(
        ['Формулировка', 'M, ч', 'LP, баллы', 'MILP, баллы', 'Интегральный зазор, %',
         'Узлы MILP', 'Медиана MILP, мс', 'y для T02 в LP'],
        [(name, r['M'], f"{r['lp_score']:.3f}", f"{r['milp_score']:.2f}",
          f"{r['integrality_gap_pct']:.3f}", r['mip_nodes'],
          f"{r['median_milp_ms']:.3f}", f"{r['lp_activation_T02']:.4f}")
         for name, r in zip(('Обоснованное M', 'Завышенное M', 'Обоснованное M с отсечениями'), comparisons)],
    )
    scaling_table = table(
        ['Кандидаты', 'Команды', 'Бинарные', 'Непрерывные', 'LP, баллы', 'MILP, баллы',
         'LP, мс', 'MILP, мс', 'Интегральный зазор, %', 'Зазор HiGHS, %', 'Узлы MILP'],
        [(r['candidates'], r['teams'], r['binary_variables'], r['continuous_variables'],
          f"{r['lp_score']:.2f}", f"{r['milp_score']:.2f}", f"{r['lp_median_ms']:.3f}",
          f"{r['milp_median_ms']:.3f}", f"{r['integrality_gap_pct']:.3f}",
          f"{r['mip_gap_pct']:.2f}", r['mip_nodes']) for r in scaling],
    )
    text = rf"""# Лабораторная работа № 3. Формирование проектных команд

Вариант **{data['variant']}**, seed **{data['seed']}**. Цель работы — сформировать три команды из 12 кандидатов с учётом ролей, совместимости и ограниченного резерва часов, затем оценить цену дискретных решений.

## 1. Исходные данные

В каждой команде нужны разработчик, аналитик и координатор. Числа в столбцах команд — баллы пригодности кандидата для проекта. Часы — вклад кандидата за расчётный период. Командам T01, T02 и T03 требуется соответственно 23, 24 и 25 часов. Каждая может запросить до 10 часов у внешнего специалиста. Открытие резерва стоит 8, 9 или 10 баллов соответственно. Каждый использованный час резерва стоит 2 балла. Баллы пригодности и расходы приведены к одной условной шкале.

{input_table}

Несовместимые пары в базе — {', '.join('/'.join(pair) for pair in data['conflicts'])}. Их нельзя назначать в одну команду. Данные синтетические и хранятся отдельно от модели в [JSON](../data/teams_12.json). Генератор создаёт оценки, часы и пары по фиксированному seed. Параметры команд и правила сценариев заданы в генераторе.

## 2. Формальная MILP-модель

- $I$ — кандидаты, $J$ — команды, $R$ — роли, $I_r$ — кандидаты роли $r$, $F$ — несовместимые пары.
- $s_{{ij}}$ — оценка назначения в баллах, $a_i$ — часы кандидата, $D_j$ — потребность команды в часах, $H_j$ — лимит внешнего резерва в часах, $u_i$ — доступность кандидата (0 или 1).
- $f_j$ — фиксированная плата за открытие резерва в баллах, $c_j$ — плата в баллах за час.
- $x_{{ij}}$ — бинарное назначение кандидата в команду. $y_j$ — бинарное включение резерва. $h_j$ — непрерывные часы внешней поддержки.

Максимизируется итоговая оценка в баллах.

$$
Z=\sum_{{i\in I,j\in J}} s_{{ij}}x_{{ij}}-\sum_{{j\in J}}(f_jy_j+c_jh_j).
$$

| Ограничение | Смысл |
| --- | --- |
| $\sum_{{j\in J}}x_{{ij}}\le1$ для $i\in I$ | Кандидат участвует максимум в одной команде |
| $x_{{ij}}\le u_i$ для $i\in I,j\in J$ | Недоступных кандидатов нельзя назначать |
| $\sum_{{i\in I_r}}x_{{ij}}=1$ для $r\in R,j\in J$ | Ровно один человек на каждую роль |
| $x_{{ij}}+x_{{kj}}\le1$ для $(i,k)\in F,j\in J$ | Несовместимая пара не работает в одной команде |
| $\sum_{{i\in I}}a_ix_{{ij}}+h_j\ge D_j$ для $j\in J$ | Покрыть потребность команды в часах |
| $0\le h_j\le H_j$ и $h_j\le M_j y_j$ для $j\in J$ | Соблюсти лимит и разрешить часы только при активации |

$x_{{ij}},y_j\in\{{0,1\}}$, $h_j\in\mathbb{{R}}$. Неделимость назначения и однократная фиксированная плата при любом положительном объёме поддержки требуют дискретных решений. В LP-релаксации $x_{{ij}}$ и $y_j$ ограничены от 0 до 1, остальные ограничения сохранены.

## 3. Решатель, решения и проверка

LP решена двойственным симплекс-методом HiGHS через `scipy.optimize.linprog` (`highs-ds`). MILP решена через `scipy.optimize.milp` с ветвлением и отсечениями HiGHS. В обоих случаях включён presolve и задан предел 15 секунд на solve. Для MILP задан `mip_rel_gap=0`. Интерфейс SciPy минимизирует, поэтому код передаёт $-Z$ и меняет знак результата и двойственной границы при выводе. Версии зафиксированы в [README](../README.md) и [requirements.txt](../requirements.txt), нативные протоколы находятся в [solver.log](solver.log).

Статус `optimal` означает, что решатель подтвердил оптимальность в численных допусках. Статус `infeasible` означает несовместность требований. `unbounded` означает, что цель не ограничена. При достижении лимита оптимальность может остаться недоказанной.

{scenario_table}

{plan_table}

Базовая LP дала **{tight['lp_score']:.2f} балла**, MILP — **{base['score']:.2f} балла**. Интегральный зазор равен $(Z_{{LP}}-Z_{{MILP}})/|Z_{{MILP}}|$ и составляет **{tight['integrality_gap_pct']:.3f}%**. LP назначила тех же людей, но для двух часов резерва T02 выбрала $y_{{T02}}={tight['lp_activation_T02']:.1f}$ и списала лишь 1,8 из 9 баллов фиксированной платы. При целочисленном включении команда платит все 9 баллов. Итоговый зазор ветвления HiGHS — другой показатель. Он сравнивает лучшее найденное целочисленное решение с глобальной границей поиска. В базе он равен **{base['mip_gap_pct']:.2f}%**, поскольку обе оценки равны {base['score']:.0f}.

Независимый проверяющий код проходит по кандидатам, ролям и парам из исходных данных. Он проверяет назначения, доступность, бинарность, часы, границы и связки big-M с абсолютным допуском $10^{{-7}}$. Цель пересчитывается отдельно по баллам и расходам. Полная детализация сохранена в [verification_details.csv](verification_details.csv).

{check_table}

## 4. Сценарии и эвристика

При отсутствии P01 команда T02 назначает P10 на роль разработчика и сохраняет два часа резерва. Оценка снижается с {base['score']:.0f} до {deficit['score']:.0f} баллов. В стрессе дополнительно недоступен P06, пара P02/P04 становится несовместимой, а каждой команде требуется на час больше. Меняются все три состава, кандидат P04 переходит в T02, а T03 запрашивает шесть часов резерва. Оценка падает до {stress['score']:.0f} баллов.

Жадная эвристика проходит команды в порядке T01, T02, T03. Для текущей команды она выбирает совместимую тройку с максимальной локальной оценкой после оплаты резерва. Уже назначенные кандидаты исключаются. Эвристика работает на тех же данных и проверяется тем же независимым кодом. Потеря рассчитывается как $(Z_{{MILP}}-Z_{{greedy}})/|Z_{{MILP}}|$.

{greedy_table}

В базе локальный выбор для T01 ограничивает последующие назначения. Наилучший состав каждой очередной команды не гарантирует максимальную оценку проекта.

## 5. Выбор big-M и дополнительная формулировка

Из ограничения $h_j\le H_j=10$ следует, что достаточно $M_j=10$ часов. Когда резерв включён, связка не ограничивает доступный объём сверх исходного лимита. Когда выключен, она запрещает внешние часы. Для опыта с $M_j=1000$ физическая граница $h_j\le10$ сохранена, поэтому допустимые целочисленные решения те же. Релаксация оплачивает лишь {large['lp_activation_T02']:.3f} фиксированной платы T02 при тех же двух часах, и верхняя граница ухудшается с {tight['lp_score']:.3f} до {large['lp_score']:.3f} балла. Отдельные замеры небольшой задачи не позволяют сделать общий вывод о влиянии M на время.

В усиленной формулировке для каждой совместимой тройки $S$, собственных часов которой недостаточно команде $j$, добавлено неравенство $\sum_{{i\in S}}x_{{ij}}\le 2+y_j$. Если назначены все трое, оно требует включить резерв. Это уже следует из исходной MILP. Если выбраны максимум двое из тройки, неравенство выполняется автоматически. Следовательно, отсечения сохраняют целочисленные планы. На этом наборе они уменьшают верхнюю границу LP до {cuts['lp_score']:.3f} балла при том же MILP-оптимуме {cuts['milp_score']:.0f}.

{formulation_table}

## 6. Рост масштаба

Сравниваются три отдельно сгенерированных набора на 12, 24 и 48 кандидатов с пропорционально растущим числом команд. Для каждого размера решены LP и MILP. Медиана получена по {repeats} запускам без печати журнала и включает построение модели и вызов решателя. Использован тот же способ измерения для сравнения формулировок и эвристики. Нативный журнал записан отдельным запуском. Абсолютное время зависит от компьютера, а три реализации данных не дают гарантии монотонности зазора.

{scaling_table}

![Медианное время и зазоры для трёх размеров задачи](scaling.png)

Рост числа команд и кандидатов увеличивает число бинарных назначений. Во всех трёх наборах HiGHS подтвердил оптимальность. Ненулевой интегральный зазор показывает разницу с полной LP-релаксацией даже при нулевом итоговом зазоре ветвления.

## 7. Практическая применимость

Базовый состав реализуем в рамках заданных ролей, часов и парных ограничений. Он требует заранее подтвердить два часа внешней поддержки для T02. Для реального проекта потребуются проверка оценок пригодности, календарей, бюджета и наличия внешних специалистов. Модель предполагает фиксированные роли, общий расчётный период и отдельный лимит внешних часов для каждой команды. Синтетические баллы подходят для сравнения планов внутри эксперимента.
"""
    path.write_text(text, encoding='utf-8')
